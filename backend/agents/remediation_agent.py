"""
Remediation Agent (Model: Gemini 2.5 Pro).
Drafts rollback / fix PRs with rich causal body and runbook update patches.
Follows Stage 4 in .agents/CODE_BACKEND.md.
"""

from __future__ import annotations
from backend.models.schema import AgentMessage, RemediationPlan, Hypothesis, VerificationBadges
from backend.engine.graph import CausalGraphEngine, engine


class RemediationAgent:
    def __init__(self, graph_engine: CausalGraphEngine = engine):
        self.engine = graph_engine

    def draft_remediation(
        self,
        incident_id: str,
        hypothesis: Hypothesis,
        verification: VerificationBadges,
    ) -> tuple[AgentMessage, RemediationPlan]:
        incident = self.engine.get_incident_node(incident_id)
        cause_node = self.engine.get_node(hypothesis.cause_node_id)

        target_repo = "enigma-sandbox/opentelemetry-demo"
        cause_title = cause_node.label if cause_node else hypothesis.cause_node_id
        pr_num = cause_node.metadata.get("number", "XXX") if cause_node else "XXX"
        orig_diff = cause_node.metadata.get("diff", "") if cause_node else ""

        # Invert diff for revert PR
        revert_diff_lines = []
        for line in orig_diff.split("\n"):
            if line.startswith("+") and not line.startswith("+++"):
                revert_diff_lines.append("-" + line[1:])
            elif line.startswith("-") and not line.startswith("---"):
                revert_diff_lines.append("+" + line[1:])
            else:
                revert_diff_lines.append(line)
        revert_diff = "\n".join(revert_diff_lines)

        # Stale runbook patch if detected
        runbook_patch = None
        if verification.stale_doc_detected and verification.superseded_doc_id:
            stale_doc = self.engine.get_node(verification.superseded_doc_id)
            if stale_doc:
                runbook_patch = (
                    f"diff --git a/docs/{verification.superseded_doc_id}.md b/docs/{verification.superseded_doc_id}.md\n"
                    f"--- a/docs/{verification.superseded_doc_id}.md\n"
                    f"+++ b/docs/{verification.superseded_doc_id}.md\n"
                    f"@@ -1,5 +1,6 @@\n"
                    f"+> **DEPRECATION WARNING:** Superseded by incident root-cause remediation for {incident_id}.\n"
                    f"-{stale_doc.metadata.get('content', '')[:100]}...\n"
                    f"+Update parameters to match verified production topology guidelines.\n"
                )

        pr_title = f"revert: fix incident {incident_id} by reverting PR #{pr_num} ({cause_title[:45]})"
        pr_branch = f"enigma/remediation-{incident_id.lower()}-pr{pr_num}"

        body_lines = [
            f"## Root Cause Remediation for Incident {incident_id}",
            f"**Affected Service:** `{incident.service_id if incident else 'unknown'}`",
            f"**Identified Root Cause:** `{hypothesis.cause_node_id}` ({cause_title})",
            "",
            "### Deterministic Graph Verifications Passed",
            f"- [x] **Temporal Precedence:** Change was merged prior to incident onset ({verification.temporal_delta_seconds / 60.0:.1f}m window).",
            f"- [x] **Topological Path:** Valid causal dependency path verified ({verification.topology_path_hops} hops: `{' -> '.join(verification.topology_path)}`).",
            f"- [x] **Adversarial Falsification:** Challenger agent disproved competing and decoy candidates.",
        ]

        if runbook_patch:
            body_lines.append(
                f"- [x] **Documentation Modernization:** Superseded runbook `{verification.superseded_doc_id}` patched in commit 2."
            )

        body_lines.extend([
            "",
            "### Proposed Action",
            "Reverts the regression diff to immediately restore service health and clear the error budget.",
            "",
            "*Draft generated by Enigma Agentic Root-Cause Engine. Awaiting human engineering lead approval.*",
        ])

        plan = RemediationPlan(
            incident_id=incident_id,
            target_repo=target_repo,
            pr_title=pr_title,
            pr_branch=pr_branch,
            pr_body="\n".join(body_lines),
            diff_preview=revert_diff,
            runbook_patch=runbook_patch,
            approved=False,
        )

        msg = AgentMessage(
            agent="remediation",
            role="Safe Draft PR Generator",
            model="gemini-2.5-pro",
            content=(
                f"**Draft Remediation Prepared:**\n"
                f"- **PR Title:** `{plan.pr_title}`\n"
                f"- **Target Sandbox Repo:** `{plan.target_repo}`\n"
                f"- **Branch:** `{plan.pr_branch}`\n"
                f"- **Runbook Update Attached:** {'Yes (superseded document patched)' if runbook_patch else 'No'}\n"
                f"\n🔒 *Remediation Agent is gated by human approval. No GitHub API writes will occur until explicit approval token is submitted.*"
            ),
            citations=[{"id": hypothesis.cause_node_id, "label": cause_title, "link": cause_node.source_link if cause_node else ""}],
            metadata={"target_branch": pr_branch, "repo": target_repo},
        )

        return msg, plan
